-- GreenPlus Docker lab ONLY. Creates/rotates a least-privileged PostgREST login.
-- Safe on both pristine and existing Docker volumes; never touches tenant rows.
-- :rest_password is a psql variable; do not echo the expanded SQL/secret.
\set QUIET on
\set ON_ERROR_STOP on
BEGIN;
DO $create_role$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'greenplus_postgrest') THEN
    CREATE ROLE greenplus_postgrest LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
END
$create_role$;
-- psql variables cannot be interpolated inside DO $$; use a properly escaped
-- literal generated by format(%L), with no echo and no plaintext in the repo.
SELECT format('ALTER ROLE greenplus_postgrest LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L', :'rest_password')
\gexec
GRANT web_anon TO greenplus_postgrest;
COMMIT;
-- The gateway routes access, while PostgREST switches to web_anon for SQL.
-- This is least-privileged *connection* hardening; demo grants are not RLS.
